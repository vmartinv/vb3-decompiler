@pytest.mark.parametrize("text, code, names", CASES, ids=[c[0] for c in CASES])
def test_lift(text, code, names):
    assert [NAMES[op] for _, op, _ in code] == [n for n, _, _ in code]
    assert lift([(op, bytes.fromhex(h)) for _, op, h in code], names=names) == text


def test_calls_record_argument_types():
    text, code, names = next(c for c in CASES if c[0].startswith("Call "))
    calls: list = []
    lift([(op, bytes.fromhex(h)) for _, op, h in code], names=names, calls=calls)
    assert calls
